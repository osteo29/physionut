import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const rootDir = process.cwd();
const mergedSourcePath = resolve(rootDir, 'physiorehab-protocols-database', 'merged_protocols.json');
const outputPath = resolve(rootDir, 'supabase', 'generated_rehab_protocol_library_seed.sql');

function escapeSql(value) {
  return String(value ?? '').replace(/'/g, "''");
}

function sqlText(value) {
  const text = String(value ?? '').trim();
  return text ? `'${escapeSql(text)}'` : 'null';
}

function sqlTextArray(values) {
  const items = (Array.isArray(values) ? values : []).map((value) => `'${escapeSql(String(value).trim())}'`);
  return `ARRAY[${items.join(', ')}]::text[]`;
}

const protocols = JSON.parse(readFileSync(mergedSourcePath, 'utf8'));

const lines = [
  '-- Generated by scripts/export-rehab-protocol-seed-sql.mjs',
  'begin;',
  '',
  'delete from public.protocols where id > 0;',
  '',
];

protocols.forEach((protocol, protocolIndex) => {
  const protocolId = protocolIndex + 1;
  lines.push(
    `insert into public.protocols (id, name, category, description) values (${protocolId}, ${sqlText(protocol.name)}, ${sqlText(protocol.category)}, null);`,
  );

  protocol.phases.forEach((phase, phaseIndex) => {
    const phaseId = protocolId * 100 + phaseIndex + 1;
    lines.push(
      `insert into public.phases (id, protocol_id, phase_number, title, timeline, goals, precautions, criteria_to_progress) values (${phaseId}, ${protocolId}, ${Number(phase.phaseNumber)}, ${sqlText(phase.title)}, ${sqlText(phase.timeline)}, ${sqlTextArray(phase.goals)}, ${sqlTextArray(phase.precautions)}, ${sqlTextArray(phase.criteriaToProgress)});`,
    );

    phase.exercises.forEach((exercise, exerciseIndex) => {
      const exerciseId = phaseId * 1000 + exerciseIndex + 1;
      lines.push(
        `insert into public.exercises (id, phase_id, name, parameters, clinical_cue_rationale) values (${exerciseId}, ${phaseId}, ${sqlText(exercise.name)}, ${sqlText(exercise.parameters)}, ${sqlText(exercise.clinicalCueRationale)});`,
      );
    });

    lines.push('');
  });
});

lines.push('commit;');
lines.push('');

writeFileSync(outputPath, lines.join('\n'), 'utf8');
console.log(JSON.stringify({protocolCount: protocols.length, outputPath}, null, 2));
